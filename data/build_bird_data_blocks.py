# ------------------------------------------------------------------- derive data
def esc(s):
    return (s or "").replace("\\", "\\\\").replace('"', '\\"')


ORDERED = [f for _, _, blocks in TREE_SPEC for _, fams in blocks for f in fams]
missing = set(FAMILY_NAMES) - set(ORDERED)
extra = set(ORDERED) - set(FAMILY_NAMES)
unwritten = set(FAMILY_NAMES) - set(FAM)
if missing or extra or unwritten or len(ORDERED) != len(set(ORDERED)):
    raise SystemExit("TREE_SPEC/FAM out of step with AviList: missing %s, extra %s, no prose %s"
                     % (sorted(missing), sorted(extra), sorted(unwritten)))

byfam = collections.OrderedDict((f, collections.OrderedDict()) for f in ORDERED)
for s in SPECIES:
    byfam[s["family"]].setdefault(s["genus"], []).append(s)

# --- F: family info
out = io.StringIO()
out.write("const F = {\n")
for fam in ORDERED:
    genera = byfam[fam]
    nsp = sum(len(v) for v in genera.values())
    rng, desc = FAM[fam]
    out.write('  %s:{common:"%s",genera:%d,species:%d,range:"%s",\n    desc:"%s"},\n'
              % (fam, esc(FAMILY_NAMES[fam]), len(genera), nsp, esc(rng), esc(desc)))
out.write("};\n")
F_JS = out.getvalue()

# --- TREE
lines = ['const TREE = {name:"Aves", rank:"Class", children:[']
for cname, crank, blocks in TREE_SPEC:
    lines.append('  {name:"%s", rank:"%s", children:[' % (cname, crank))
    for bname, fams in blocks:
        leaves = ", ".join('leaf("%s")' % f for f in fams)
        lines.append('    {name:"%s", rank:"Order", children:[ %s ]},' % (bname, leaves))
    lines.append("  ]},")
lines.append("]};")
TREE_JS = "\n".join(lines) + "\n"

# --- ATLAS: genus lists only. The page rebuilds ATLAS and SP from the full
# taxonomy as soon as it loads; this is what the tree can open before then.
out = io.StringIO()
out.write("const ATLAS = {\n")
for fam in ORDERED:
    gl = ",".join('["%s",%d]' % (g, len(v)) for g, v in byfam[fam].items())
    out.write("%s:P([%s]),\n" % (fam, gl))
out.write("};\n")
ATLAS_JS = out.getvalue()

# --- SP: empty. Eleven thousand species inline would triple the page for no
# gain -- genera open to species once bird_taxonomy.json has loaded.
SP_JS = "const SP = {\n};\n"

blocks = "\n".join([F_JS, TREE_JS, ATLAS_JS, SP_JS])

if __name__ == "__main__":
    print("families %d, genera %d, species %d; F block %d KB, ATLAS block %d KB" % (
        len(ORDERED), len({s["genus"] for s in SPECIES}), len(SPECIES),
        len(F_JS) / 1024, len(ATLAS_JS) / 1024))
