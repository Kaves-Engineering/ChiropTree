"""Build marine-mammal-tree.html from chiroptera-tree.html.

Run:  uv run python data/build_marine_mammal_page.py

chiroptera-tree.html is the master. This copies it verbatim and swaps only
content: prose, the four hand-authored data blocks (generated by gen_marine.py
from MDD), the data-file paths, and the strings that name the animals. Every
replacement is anchored on an exact string and fails loudly if it misses, so
the two pages cannot silently drift apart structurally.
"""
