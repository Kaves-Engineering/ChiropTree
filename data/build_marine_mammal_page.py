blocks = data.blocks

def grab(name):
    """Pull one generated const block out of blocks.js.

    TREE is an array literal and closes on "]};" rather than "};" -- without
    that alternative the non-greedy match runs straight past it and swallows
    the next block whole.
    """
    m = re.search(r"^const %s = .*?^\]?};$" % name, blocks, re.S | re.M)
    if not m:
        sys.exit("generated block not found: " + name)
    return m.group(0)

hits = []
def sub(old, new, count=1):
    global html
    n = html.count(old)
    if n != count:
        sys.exit("ANCHOR MISS (%d, expected %d): %s" % (n, count, old[:90].replace("\n", " ")))
    html = html.replace(old, new)
    hits.append(old[:60].replace("\n", " "))

def sub_region(start, end, new):
    """Replace from `start` through `end` inclusive."""
    global html
    i = html.find(start)
    j = html.find(end, i)
    if i < 0 or j < 0:
        sys.exit("REGION MISS: %s ... %s" % (start[:60], end[:60]))
    html = html[:i] + new + html[j + len(end):]
    hits.append("region " + start[:50].replace("\n", " "))

